create table if not exists public.autoelevador_mensual (
  id bigint generated by default as identity primary key,
  periodo_id uuid not null references public.periodos(id) on delete cascade,
  empleado_id uuid not null references public.empleados(id) on delete cascade,
  turno text not null, mes_texto text, dias_trabajados integer default 0,
  tiempo_efectivo_segundos bigint default 0, tiempo_muerto_segundos bigint default 0,
  tiempo_ralenti_segundos bigint default 0, horas_netas_segundos bigint default 0,
  objetivo_segundos bigint default 0, rendimiento numeric default 0,
  variacion_ultimo_mes numeric, variacion_desde_inicio numeric, promedio_ponderado numeric,
  mejor_mes text, tendencia text, created_at timestamptz default now(),
  unique(periodo_id,empleado_id,turno)
);
create table if not exists public.autoelevador_diario (
  id bigint generated by default as identity primary key,
  periodo_id uuid not null references public.periodos(id) on delete cascade,
  empleado_id uuid not null references public.empleados(id) on delete cascade,
  fecha date not null, turno text not null,
  tiempo_efectivo_segundos bigint default 0, tiempo_muerto_segundos bigint default 0,
  tiempo_ralenti_segundos bigint default 0, horas_netas_segundos bigint default 0,
  objetivo_segundos bigint default 0, rendimiento numeric default 0,
  diferencia_segundos bigint default 0, estado text, created_at timestamptz default now(),
  unique(periodo_id,empleado_id,fecha,turno)
);
create table if not exists public.autoelevador_pausas (
  id bigint generated by default as identity primary key,
  periodo_id uuid not null references public.periodos(id) on delete cascade,
  empleado_id uuid not null references public.empleados(id) on delete cascade,
  fecha date not null, turno text not null, inicio text, fin text,
  duracion_segundos bigint default 0, duracion_minutos numeric default 0,
  tipo text, clasificacion text, mes_texto text, created_at timestamptz default now()
);
create table if not exists public.autoelevador_horario (
  id bigint generated by default as identity primary key,
  periodo_id uuid not null references public.periodos(id) on delete cascade,
  empleado_id uuid not null references public.empleados(id) on delete cascade,
  fecha date not null, turno text not null, etiquetas jsonb not null default '[]'::jsonb,
  valores_segundos jsonb not null default '[]'::jsonb, created_at timestamptz default now(),
  unique(periodo_id,empleado_id,fecha,turno)
);

alter table public.autoelevador_mensual enable row level security;
alter table public.autoelevador_diario enable row level security;
alter table public.autoelevador_pausas enable row level security;
alter table public.autoelevador_horario enable row level security;

-- Un administrador puede leer y administrar todos los registros.
do $$ declare t text; begin
  foreach t in array array['autoelevador_mensual','autoelevador_diario','autoelevador_pausas','autoelevador_horario'] loop
    execute format('drop policy if exists auto_admin_all on public.%I',t);
    execute format($p$create policy auto_admin_all on public.%I for all to authenticated using (exists (select 1 from public.perfiles p where p.auth_user_id=auth.uid() and p.rol='administrador')) with check (exists (select 1 from public.perfiles p where p.auth_user_id=auth.uid() and p.rol='administrador'))$p$,t);
  end loop;
end $$;

-- Cada persona solo puede leer sus propios registros.
do $$ declare t text; begin
  foreach t in array array['autoelevador_mensual','autoelevador_diario','autoelevador_pausas','autoelevador_horario'] loop
    execute format('drop policy if exists auto_personal_select on public.%I',t);
    execute format($p$create policy auto_personal_select on public.%I for select to authenticated using (empleado_id in (select p.empleado_id from public.perfiles p where p.auth_user_id=auth.uid()))$p$,t);
  end loop;
end $$;

create index if not exists idx_auto_mensual_emp_periodo on public.autoelevador_mensual(empleado_id,periodo_id);
create index if not exists idx_auto_diario_emp_fecha on public.autoelevador_diario(empleado_id,fecha);
create index if not exists idx_auto_pausas_emp_fecha on public.autoelevador_pausas(empleado_id,fecha);
create index if not exists idx_auto_horario_emp_fecha on public.autoelevador_horario(empleado_id,fecha);
