-- Control de logueo en autoelevadores: cada persona ve el suyo y el administrador ve todos.
create table if not exists public.autoelevador_logueo (
  id bigint generated by default as identity primary key,
  empleado_id uuid not null references public.empleados(id) on delete cascade,
  legajo text, operador text, fecha date not null, turno text not null,
  hora_esperada text, primer_logueo text, minutos_diferencia integer,
  resultado text, semaforo text, hora_final text,
  ae_inicial text, ae_utilizados text, tipo_ae text, horas_ae numeric, eventos integer,
  ultimo_uso text, archivo text, created_at timestamptz default now()
);
create index if not exists idx_logueo_fecha on public.autoelevador_logueo(fecha);
create index if not exists idx_logueo_empleado on public.autoelevador_logueo(empleado_id, fecha);
create table if not exists public.autoelevador_logueo_mensual (
  id bigint generated by default as identity primary key,
  empleado_id uuid not null references public.empleados(id) on delete cascade,
  legajo text, operador text, anio integer not null, mes integer not null, turnos text,
  verde integer default 0, amarillo integer default 0, rojo integer default 0, demorados integer default 0,
  dias integer default 0, pct_verde numeric, resultado text, observacion text, archivo text, created_at timestamptz default now()
);
create index if not exists idx_logueo_mensual on public.autoelevador_logueo_mensual(anio, mes);
do $$ declare t text; begin
  foreach t in array array['autoelevador_logueo','autoelevador_logueo_mensual'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('grant select,insert,update,delete on public.%I to authenticated', t);
    execute format('drop policy if exists logueo_admin_all on public.%I', t);
    execute format($p$create policy logueo_admin_all on public.%I for all to authenticated using (exists (select 1 from public.perfiles p where p.auth_user_id=auth.uid() and p.rol='administrador')) with check (exists (select 1 from public.perfiles p where p.auth_user_id=auth.uid() and p.rol='administrador'))$p$, t);
    execute format('drop policy if exists logueo_personal_select on public.%I', t);
    execute format($p$create policy logueo_personal_select on public.%I for select to authenticated using (empleado_id in (select p.empleado_id from public.perfiles p where p.auth_user_id=auth.uid()))$p$, t);
  end loop;
end $$;
grant usage, select on all sequences in schema public to authenticated;
