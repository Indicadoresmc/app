create table if not exists public.autoelevador_break_tandas (
  id bigint generated by default as identity primary key,
  turno text not null check (turno in ('Mañana','Tarde','Noche')),
  nombre text not null,
  inicio time not null,
  fin time not null,
  duracion_prevista_min integer not null default 30 check (duracion_prevista_min > 0),
  activa boolean not null default true,
  created_at timestamptz not null default now(),
  unique(turno,nombre)
);
create table if not exists public.autoelevador_break_asignaciones (
  id bigint generated by default as identity primary key,
  empleado_id uuid not null references public.empleados(id) on delete cascade,
  tanda_id bigint not null references public.autoelevador_break_tandas(id) on delete cascade,
  vigente_desde date not null default current_date,
  vigente_hasta date,
  activa boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists idx_break_asig_empleado on public.autoelevador_break_asignaciones(empleado_id,activa);
alter table public.autoelevador_break_tandas enable row level security;
alter table public.autoelevador_break_asignaciones enable row level security;
grant select,insert,update,delete on public.autoelevador_break_tandas to authenticated;
grant select,insert,update,delete on public.autoelevador_break_asignaciones to authenticated;
grant usage,select on all sequences in schema public to authenticated;
drop policy if exists break_tandas_select on public.autoelevador_break_tandas;
create policy break_tandas_select on public.autoelevador_break_tandas for select to authenticated using (true);
drop policy if exists break_tandas_admin on public.autoelevador_break_tandas;
create policy break_tandas_admin on public.autoelevador_break_tandas for all to authenticated using (exists(select 1 from public.perfiles p where p.auth_user_id=auth.uid() and p.rol='administrador')) with check (exists(select 1 from public.perfiles p where p.auth_user_id=auth.uid() and p.rol='administrador'));
drop policy if exists break_asig_personal on public.autoelevador_break_asignaciones;
create policy break_asig_personal on public.autoelevador_break_asignaciones for select to authenticated using (empleado_id in (select p.empleado_id from public.perfiles p where p.auth_user_id=auth.uid()));
drop policy if exists break_asig_admin on public.autoelevador_break_asignaciones;
create policy break_asig_admin on public.autoelevador_break_asignaciones for all to authenticated using (exists(select 1 from public.perfiles p where p.auth_user_id=auth.uid() and p.rol='administrador')) with check (exists(select 1 from public.perfiles p where p.auth_user_id=auth.uid() and p.rol='administrador'));
